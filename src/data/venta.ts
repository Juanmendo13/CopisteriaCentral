export function formatEuro(n: number): string {
  return new Intl.NumberFormat('es-ES', { style: 'currency', currency: 'EUR' }).format(n);
}

export function getVentaItem(id: string): VentaItem | undefined {
  return venta.find((p) => p.id === id);
}

export function ventaConImagenes(): VentaItem[] {
  return venta.map((item) => ({ ...item, image: getVentaImage(item.id) }));
}

export function ventaPorCategoria(): { categoria: string; items: VentaItem[] }[] {
  return ventaCategorias
    .map((categoria) => ({
      categoria,
      items: venta.filter((p) => p.categoria === categoria).map((item) => ({
        ...item,
        image: getVentaImage(item.id),
      })),
    }))
    .filter((g) => g.items.length > 0);
}
